"""Bake ASCII 32-126 from a TTF into a C header of 8-bit alpha glyphs.

Usage: make_font.py FONT.ttf OUT.h name:size [name:size ...]
Used at build time so the pak needs no SDL_ttf or font files on the device.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path, out_path, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
out = ["/* Generated by tools/make_font.py. Do not edit. */", "#pragma once", "#include <stdint.h>",
       "typedef struct { int w, h, advance; const uint8_t *alpha; } Glyph;",
       "typedef struct { int height, ascent; Glyph glyphs[95]; } BakedFont;", ""]
for spec in specs:
    name, size = spec.split(":")
    size = int(size)
    f = ImageFont.truetype(font_path, size)
    ascent, descent = f.getmetrics()
    height = ascent + descent
    entries = []
    for c in range(32, 127):
        ch = chr(c)
        adv = int(round(f.getlength(ch)))
        w = max(adv, 1)
        img = Image.new("L", (w, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=f, fill=255)
        data = img.tobytes()
        var = f"{name}_g{c}"
        out.append(f"static const uint8_t {var}[] = {{" + ",".join(str(b) for b in data) + "};")
        entries.append(f"{{{w},{height},{adv},{var}}}")
    out.append(f"static const BakedFont {name} = {{{height},{ascent},{{" + ",".join(entries) + "}};")
    out.append("")
open(out_path, "w").write("\n".join(out))
